#!/usr/bin/env node
/**
 * Local OpenAI-compatible stub used ONLY to verify PatchPilot's live provider
 * plumbing when no hosted model credential is available. It is not a model and
 * makes no AI decisions: it returns fixed JSON so the HTTP, schema, evidence,
 * and UI paths can be exercised end to end.
 *
 * Usage:
 *   node scripts/mock-openai-server.mjs
 *   LLM_BASE_URL=http://127.0.0.1:8788/v1 LLM_MODEL=plumbing-test pnpm dev
 *
 * Do not deploy this stub. It is not part of the product.
 */
import { createServer } from "node:http";

const PORT = Number(process.env.MOCK_PORT || 8788);

const REVIEW = {
  summary:
    "Local stub response: one evidence-backed SQL injection finding. This is fixed test data, not a model answer.",
  findings: [
    {
      title: "SQL injection in the coupon lookup",
      severity: "critical",
      category: "security",
      file: "src/checkout.ts",
      lineStart: 1,
      lineEnd: 1,
      evidence: [
        "  const cart = await db.query(",
        "    `SELECT * FROM carts WHERE id = '${cartId}'`",
        "  );",
      ].join("\n"),
      explanation:
        "cartId is interpolated into a SQL string, so caller-controlled text changes the query.",
      fix: "Use a parameterized query: db.query('SELECT * FROM carts WHERE id = $1', [cartId]).",
      confidence: 0.94,
    },
    {
      title: "Fabricated finding that must be dropped",
      severity: "high",
      category: "bug",
      file: "src/checkout.ts",
      lineStart: 2,
      lineEnd: 2,
      evidence: "this code does not exist in the submission",
      explanation: "PatchPilot should discard this because the evidence is not present.",
      fix: "Nothing to fix.",
      confidence: 0.9,
    },
  ],
  limitations: ["Generated by a local plumbing stub, not a model."],
};

const TESTS = {
  summary: "Local stub test suggestion.",
  framework: "Vitest",
  cases: [
    {
      title: "parameterizes the cart id",
      rationale: "Protects the SQL path exercised by the review.",
      code: 'it("parameterizes", async () => { await applyCoupon("cart_1", "SAVE20"); });',
    },
  ],
};

function completion(content) {
  return {
    choices: [{ message: { content }, finish_reason: "stop" }],
    usage: { prompt_tokens: 120, completion_tokens: 60 },
  };
}

const server = createServer((request, response) => {
  if (request.method === "GET" && request.url?.endsWith("/models")) {
    response.writeHead(200, { "content-type": "application/json" });
    response.end(JSON.stringify({ data: [{ id: "plumbing-test", object: "model" }] }));
    return;
  }

  if (request.method !== "POST" || !request.url?.endsWith("/chat/completions")) {
    response.writeHead(404, { "content-type": "application/json" });
    response.end(JSON.stringify({ error: "not found" }));
    return;
  }

  let raw = "";
  request.on("data", (chunk) => {
    raw += chunk;
    if (raw.length > 250_000) request.destroy();
  });

  request.on("end", () => {
    let body;
    try {
      body = JSON.parse(raw);
    } catch {
      response.writeHead(400, { "content-type": "application/json" });
      response.end(JSON.stringify({ error: "invalid json" }));
      return;
    }

    const system = body.messages?.find((message) => message.role === "system")?.content || "";
    let content;

    if (system.includes("suggest focused automated tests")) {
      content = JSON.stringify(TESTS);
    } else if (system.includes("discussing a code review")) {
      content =
        "Live provider plumbing works. This answer came from the local OpenAI-compatible stub, not a hosted model.";
    } else {
      content = JSON.stringify(REVIEW);
    }

    // Log only routing information, never prompts or submitted source.
    console.log(`stub: POST ${request.url} (${system.slice(0, 32)}…)`);
    response.writeHead(200, { "content-type": "application/json" });
    response.end(JSON.stringify(completion(content)));
  });
});

server.listen(PORT, "127.0.0.1", () => {
  console.log(`OpenAI-compatible plumbing stub on http://127.0.0.1:${PORT}/v1`);
  console.log("Fixed responses only. Not a model. Do not deploy.");
});